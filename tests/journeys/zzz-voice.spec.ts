import { expect, test } from '@playwright/test';

test('voice draft previews synthetic WAV by keyboard at 320px', async ({ browser }) => {
  const page = await browser.newPage({ viewport: { width: 320, height: 800 } });
  await page.goto('/app/tenants/01994f64-6c00-7000-8000-000000000002/employees');
  await page.getByRole('button', { name: 'Создать ИИ-сотрудника' }).click();
  await page.getByLabel('Назначение', { exact: true }).fill('Тестовые ответы');
  await page.getByLabel('Имя', { exact: true }).fill('Аня');
  await page.getByLabel('Языки, по одному на строке').fill('ru');
  await page.getByLabel('Часовой пояс (например, Europe/Moscow)').fill('Europe/Moscow');
  await page.getByRole('checkbox', { name: 'Понедельник' }).check();
  await page.getByLabel('Начало рабочего дня').fill('09:00');
  await page.getByLabel('Конец рабочего дня').fill('18:00');
  await page.getByRole('group', { name: 'Желаемые каналы (не подключены)' }).getByRole('checkbox', { name: 'Телефон' }).check();
  await page.getByLabel('Основные задачи, по одной на строке').fill('Ответ');
  await page.getByRole('button', { name: 'Сохранить Brief' }).click();
  await page.getByLabel('Профиль и язык').selectOption('ru-neutral-1');
  await page.getByLabel('Причина изменения голоса').fill('Первый профиль');
  await page.getByRole('button', { name: 'Сохранить новую версию голоса' }).click();
  await expect(page.getByText('Версия голоса 1')).toBeVisible();
  await page.getByLabel('Исходное написание').fill('VIN');
  await page.locator('.voice-form').getByLabel('Область применения').fill('Тест');
  await page.getByLabel('Нормализованное произношение').fill('вин');
  await page.getByLabel('Тестовая фраза с точным исходным написанием один раз').fill('Прочтите VIN');
  await page.getByLabel('Критическая сущность').selectOption('vin');
  await page.getByRole('checkbox', { name: /новая запись содержит только вымышленные/ }).check();
  await page.getByLabel('Сегменты readback критической сущности, по одному на строке').fill('V\nI\nN');
  await page.getByLabel('Причина изменения голоса').fill('Добавлен VIN');
  await page.getByRole('button', { name: 'Сохранить новую версию голоса' }).click();
  await expect(page.getByText('Версия голоса 2')).toBeVisible();
  await page.getByRole('button', { name: 'Прочтите VIN' }).click();
  await page.getByRole('checkbox', { name: /этот preview содержит только вымышленные/ }).check();
  const preview = page.getByRole('button', { name: 'Прослушать или проверить доступность' });
  await preview.focus();
  await expect(preview).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('#voice-preview-status')).toContainText('Маршрут: offline-test-tts');
  await expect(page.locator('#voice-preview-status')).toContainText('Исходный текст: Прочтите VIN');
  await expect(page.locator('#voice-preview-status')).toContainText('Синтезируемый текст: Прочтите вин');
  await expect(page.locator('#voice-preview-audio')).toBeVisible();
  await expect(page.getByRole('button', { name: /образец прослушан полностью и одобрен/ })).toBeEnabled();
  await page.getByRole('button', { name: /образец прослушан полностью и одобрен/ }).click();
  await expect(page.locator('#voice-assessment-status')).toContainText('Оценка сохранена для версии 2');
  await page.getByLabel('Темп (80–120)').fill('90');
  await page.getByLabel('Причина изменения голоса').fill('Новый темп');
  await page.getByRole('button', { name: 'Сохранить новую версию голоса' }).click();
  await expect(page.getByText('Статус: stale; нужна новая проверка.')).toBeVisible();
  await page.route('**/voice/preview', async route => { await new Promise(resolve => setTimeout(resolve, 300)); await route.continue(); });
  await page.getByRole('checkbox', { name: /этот preview содержит только вымышленные/ }).check();
  const pendingPreview = page.waitForResponse(response => response.url().endsWith('/voice/preview'));
  await page.getByRole('button', { name: 'Прослушать или проверить доступность' }).click();
  await page.getByLabel('Точный исходный текст').fill('Другой синтетический пример.');
  await pendingPreview;
  await expect(page.getByRole('button', { name: /образец прослушан полностью и одобрен/ })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Требует исправления' })).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBe(0);
  await page.close();
});
