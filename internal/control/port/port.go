// The consumer-owned ports of the control module (step-02 of story 3-2).
// The control module never imports the connector or identity modules:
// the composition root adapts their live surfaces to these contracts
// (the action-module 3-1 precedent of the consumer-owned resolvers).

// ConnectorRefResolver resolves a connector scope ref against the LIVE
// connector registry of the tenant (the 1-8 integration catalog). The
// lexical shape of the ref is checked by the domain dictionary — this
// port is the LIVE half of the honest boundary: a ref that does not
// resolve in the tenant's own registry is refused with an honest cause,
// fail-closed (the ref of a foreign or unknown connector can never
// become a control point). An infrastructure failure is an error, NEVER
// a silent "not found" — a broken registry refuses honestly loud.
type ConnectorRefResolver interface {
	// Resolve reports whether connectorID resolves in the live registry
	// of the tenant.
	Resolve(ctx context.Context, tenantID id.UUID, connectorID string) (bool, error)
}

// SetParams is one atomic Set mutation of a control point. The scope of
// the tenancy context carries the RLS identity; the IDs (audit row, outbox
// event, correlation) are generated by the app BEFORE the transaction so
// the store stays a pure persistence boundary (the employee SaveParams
// precedent). Now is the app clock — the store canonicalizes to UTC at
// the write boundary.
type SetParams struct {
	Scope              tenancy.Context
	Kind, Ref          string
	Mode, Reason       string
	ExpectedGeneration int64
	// ScheduledStartAt/ExpiresAt open and close the read-time window
	// [start, expires); nil means unbounded on that side.
	ScheduledStartAt, ExpiresAt     *time.Time
	AuditID, EventID, CorrelationID id.UUID
	Now                             time.Time
}

// ResumeParams is one atomic Resume (lift) mutation. Resume is a state
// change, NOT a deletion: the row survives, the generation grows.
type ResumeParams struct {
	Scope                           tenancy.Context
	Kind, Ref, Reason               string
	ExpectedGeneration              int64
	AuditID, EventID, CorrelationID id.UUID
	Now                             time.Time
}

// Repository is the persistence contract of the control module. Set and
// Resume are EACH one PG transaction: the advisory lock of the material
// identity, the SELECT FOR UPDATE of the scope pair, the expected
// generation check, the row write, the append-only audit row (applied OR
// conflict — both attempts stay material, AC-11) and the outbox event
// land together (AD-13 atomicity) or not at all.
//
// The conflict contract: when the expected generation does not match the
// stored one, the repository COMMITS the audit row with
// outcome='conflict' (the refused attempt is history too) and returns a
// domain.ConflictError carrying the CURRENT material — the second
// operator re-confirms over the actual state, nothing is silently
// overwritten.
type Repository interface {
	// Set atomically installs or re-installs the control point. A missing
	// point with ExpectedGeneration 0 is the first installation
	// (generation becomes 1); a missing point with a non-zero expectation
	// is the honest ErrNotFound — there is no material to confirm over.
	Set(ctx context.Context, p SetParams) (domain.ScopedControl, error)

	// Resume atomically lifts the control point (state 'removed', the
	// generation grows). A missing point is the honest ErrNotFound;
	// lifting a point that is already removed is a RuleError — repeating
	// a removal is not a state change and does not pretend to be one.
	Resume(ctx context.Context, p ResumeParams) (domain.ScopedControl, error)

	// List returns every control point of the tenant (both states — the
	// history stays readable), newest-first.
	List(ctx context.Context, scope tenancy.Context) ([]domain.ScopedControl, error)

	// LoadKeys returns the control points matching the route scope keys
	// (the EffectiveFor read). Duplicate keys collapse; the caller has
	// already validated the dictionary discipline of every key.
	LoadKeys(ctx context.Context, scope tenancy.Context, keys []domain.ScopeKey) ([]domain.ScopedControl, error)
}
